CREATE TABLE CATEGORY_TABLE (
    CATEGORY_ID INT PRIMARY KEY AUTO_INCREMENT,
    CATEGORY_NAME VARCHAR(45) NOT NULL
);

CREATE TABLE BRAND_TABLE (
    BRAND_ID INT PRIMARY KEY AUTO_INCREMENT,
    BRAND_NAME VARCHAR(45) NOT NULL,
    BRAND_COMPANY_BASED VARCHAR(45)
);

CREATE TABLE STATUS_TABLE (
    STATUS_ID INT PRIMARY KEY AUTO_INCREMENT,
    STATUS_UPDATE VARCHAR(45) NOT NULL
);

CREATE TABLE REASON_TABLE (
    REASON_ID INT PRIMARY KEY AUTO_INCREMENT,
    RETURN_REASON MEDIUMTEXT NOT NULL
);

CREATE TABLE PRODUCT_TABLE (
    PRODUCT_ID INT PRIMARY KEY AUTO_INCREMENT,
    PRODUCT_NAME VARCHAR(80) NOT NULL,
    FK_CATEGORY_ID INT NOT NULL,
    FK_BRAND_ID INT NOT NULL,
    MRP_PRICE INT NOT NULL,
    D_MART_PRICE INT NOT NULL,
    DISCOUNT DECIMAL(4,2) NOT NULL,
    EXPIRY_DATE DATE,
    FOREIGN KEY (FK_CATEGORY_ID) REFERENCES CATEGORY_TABLE(CATEGORY_ID),
    FOREIGN KEY (FK_BRAND_ID) REFERENCES BRAND_TABLE(BRAND_ID)
);

CREATE TABLE BRANCH_TABLE (
    BRANCH_ID INT PRIMARY KEY AUTO_INCREMENT,
    BRANCH_NAME VARCHAR(45) NOT NULL,
    BRANCH_LOCATION VARCHAR(45) NOT NULL,
    BRANCH_CODE VARCHAR(45) NOT NULL,
    FK_STATUS_ID INT NOT NULL,
    FOREIGN KEY (FK_STATUS_ID) REFERENCES STATUS_TABLE(STATUS_ID)
);

CREATE TABLE CUSTOMER_TABLE (
    CUSTOMER_ID INT PRIMARY KEY AUTO_INCREMENT,
    CUSTOMER_NAME VARCHAR(60) NOT NULL,
    CUSTOMER_PHONENO BIGINT NOT NULL,
    CUSTOMER_EMAIL VARCHAR(60),
    CUSTOMER_GENDER VARCHAR(45),
    CUSTOMER_CITY VARCHAR(45)
);

CREATE TABLE ORDER_TABLE (
    ORDER_ID INT PRIMARY KEY AUTO_INCREMENT,
    FK_CUSTOMER_ID INT NOT NULL,
    GRAND_TOTAL INT NOT NULL,
    FK_BRANCH_ID INT NOT NULL,
    ORDER_DATE TIMESTAMP NOT NULL,
    FOREIGN KEY (FK_CUSTOMER_ID) REFERENCES CUSTOMER_TABLE(CUSTOMER_ID),
    FOREIGN KEY (FK_BRANCH_ID) REFERENCES BRANCH_TABLE(BRANCH_ID)
);

CREATE TABLE ORDER_ITEM_TABLE (
    ORDER_ITEM_ID INT PRIMARY KEY AUTO_INCREMENT,
    FK_ORDER_ID INT NOT NULL,
    FK_PRODUCT_ID INT NOT NULL,
    QUANTITY INT NOT NULL,
    UNIT_PRICE INT NOT NULL,
    LINE_TOTAL INT NOT NULL,
    FOREIGN KEY (FK_ORDER_ID) REFERENCES ORDER_TABLE(ORDER_ID),
    FOREIGN KEY (FK_PRODUCT_ID) REFERENCES PRODUCT_TABLE(PRODUCT_ID)
);

CREATE TABLE PAYMENT_TABLE (
    PAYMENT_ID INT PRIMARY KEY AUTO_INCREMENT,
    FK_ORDER_ID INT NOT NULL,
    METHOD VARCHAR(45) NOT NULL,
    TOTAL_AMOUNT INT NOT NULL,
    PAYMENT_DATE DATE NOT NULL,
    FOREIGN KEY (FK_ORDER_ID) REFERENCES ORDER_TABLE(ORDER_ID)
);

CREATE TABLE REVIEW_TABLE (
    REVIEW_ID INT PRIMARY KEY AUTO_INCREMENT,
    FK_CUSTOMER_ID INT NOT NULL,
    FK_ORDER_ITEM_ID INT NOT NULL,
    RATING TINYINT NOT NULL,
    FOREIGN KEY (FK_CUSTOMER_ID) REFERENCES CUSTOMER_TABLE(CUSTOMER_ID),
    FOREIGN KEY (FK_ORDER_ITEM_ID) REFERENCES ORDER_ITEM_TABLE(ORDER_ITEM_ID)
);

CREATE TABLE RETURN_TABLE (
    RETURN_ID INT PRIMARY KEY AUTO_INCREMENT,
    FK_ORDER_ITEM_ID INT NOT NULL,
    FK_RETURN_REASON_ID INT NOT NULL,
    QUANTITY INT NOT NULL,
    REFUND_AMOUNT INT NOT NULL,
    RETURN_DATE DATE NOT NULL,
    FOREIGN KEY (FK_ORDER_ITEM_ID) REFERENCES ORDER_ITEM_TABLE(ORDER_ITEM_ID),
    FOREIGN KEY (FK_RETURN_REASON_ID) REFERENCES REASON_TABLE(REASON_ID)
);

